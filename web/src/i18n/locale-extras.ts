function setDeep(target: Record<string, unknown>, path: string, value: string) {
  const parts = path.split('.');
  let current = target;

  for (const part of parts.slice(0, -1)) {
    const next = current[part];
    if (!next || typeof next !== 'object') {
      current[part] = {};
    }
    current = current[part] as Record<string, unknown>;
  }

  const leaf = parts[parts.length - 1];
  current[leaf] = value;
}

export function applyLocaleExtras(language: string, resource: ResourceLanguage) {
  const key = languageAliases[language] || language;
  const firewallModerateExtras = key === 'en' || key === 'ru' ? {} : firewallModerateFallbackExtras;
  const usbWakeupExtras =
    key === 'en' || key === 'ru' ? {} : usbWakeupLocalizedExtras[key] || usbWakeupFallbackExtras;
  const deviceTipExtras =
    key === 'en' || key === 'ru' ? {} : deviceTipLocalizedExtras[key] || deviceTipFallbackExtras;
  const downloadCanceledExtras =
    key === 'en' || key === 'ru'
      ? {}
      : downloadCanceledLocalizedExtras[key] || downloadCanceledFallbackExtras;
  const mobileControlExtras =
    key === 'en' || key === 'ru'
      ? {}
      : mobileControlLocalizedExtras[key] || mobileControlFallbackExtras;
  const layoutModeExtras =
    key === 'en' || key === 'ru' ? {} : layoutModeLocalizedExtras[key] || layoutModeFallbackExtras;
  const virtualMediaExtras =
    key === 'en' || key === 'ru'
      ? {}
      : virtualMediaLocalizedExtras[key] || virtualMediaFallbackExtras;
  const downloadTransferExtras =
    key === 'en' || key === 'ru'
      ? {}
      : downloadTransferLocalizedExtras[key] || downloadTransferFallbackExtras;
  const firewallNoWebrtcExtras =
    firewallNoWebrtcLocalizedExtras[key] || firewallNoWebrtcFallbackExtras;
  const firewallNoWebrtcModeDescriptionExtras =
    firewallNoWebrtcModeDescriptionLocalizedExtras[key] ||
    firewallNoWebrtcModeDescriptionFallbackExtras;
  const extras = {
    ...(downloadExtras[key] || {}),
    ...(downloadOkExtras[key] || {}),
    ...downloadTransferExtras,
    ...(systemActionExtras[key] || {}),
    ...usbWakeupExtras,
    ...deviceTipExtras,
    ...downloadCanceledExtras,
    ...mobileControlExtras,
    ...layoutModeExtras,
    ...virtualMediaExtras,
    ...(networkExtras[key] || {}),
    ...(hardenedCommonExtras[key] || {}),
    ...(legacyExtras[key] || {}),
    ...(systemUpdateExtras[key] || {}),
    ...(firewallExtras[key] || {}),
    ...firewallModerateExtras,
    ...(firewallModerateLocalizedExtras[key] || {}),
    ...(timeLogExtras[key] || {}),
    ...firewallNoWebrtcExtras,
    ...firewallNoWebrtcModeDescriptionExtras,
    ...(totpLocalizedExtras[key] || totpFallbackExtras),
    ...(termLocalizedExtras[key] || {}),
    ...(translationFixes[key] || {})
  };
  if (!Object.keys(extras).length) return;

  const typedResource = resource as { translation?: Record<string, unknown> };
  typedResource.translation ??= {};

  for (const [path, value] of Object.entries(extras)) {
    setDeep(typedResource.translation, path, value);
  }
}
